#!/usr/bin/env swift
// Writes Sources/AllInOneIMECore/RedactionWordList.swift, the English words the key detector knows
// (`RedactionWords.english`), so that the core has them on every system: before, it read /usr/share/dict/words, which
// only Macs and some Linux systems have.
//
//   swift Scripts/make-redaction-words.swift    (make redaction-words) from /usr/share/dict/web2
//
// web2 is Webster's Second International (1934), public domain (THIRD_PARTY_NOTICES.md); on macOS
// /usr/share/dict/words is a link to it. Only the copy whose SHA-256 is pinned here is taken, so that the list never
// changes unnoticed. Its words as the core read them: each line of 3 characters or more, lowercased; deduplicated and
// sorted. The file holds one string literal per first letter, a word a line, so that no literal is huge.

import CryptoKit
import Foundation

let source = "/usr/share/dict/web2"
let pinnedSHA256 = "be41ad97963bf8dabedd5871d5d691596175269d540956b0f9965a885c2bbab9"
let output = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
    .appendingPathComponent("Sources/AllInOneIMECore/RedactionWordList.swift")

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("make-redaction-words: \(message)\n".utf8))
    exit(1)
}

guard let data = FileManager.default.contents(atPath: source) else { fail("can't read \(source)") }
let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
guard digest == pinnedSHA256 else { fail("\(source) isn't the pinned copy (SHA-256 \(digest), not \(pinnedSHA256))") }

// As RedactionWords read the system's list: lines of 3 characters or more, lowercased.
let text = String(decoding: data, as: UTF8.self)
let words = Set(text.split(separator: "\n").filter { $0.count >= 3 }.map { $0.lowercased() }).sorted()
let letters = "abcdefghijklmnopqrstuvwxyz".map(String.init)
var byLetter: [String: [String]] = [:]
for word in words {
    guard let first = word.first.map(String.init), letters.contains(first),
          word.allSatisfy({ $0.isASCII && ($0.isLetter || $0 == "-") }) else { fail("unexpected word: \(word.debugDescription)") }
    byLetter[first, default: []].append(word)
}

var file = """
    // Generated by Scripts/make-redaction-words.swift (make redaction-words) from \(source), Webster's Second International
    // (1934, public domain; THIRD_PARTY_NOTICES.md). Don't edit: run it again.

    /// The English words the key detector knows (`RedactionWords.english`): \(source)'s lines of 3 characters or more,
    /// lowercased, deduplicated and sorted; one literal per first letter, a word a line.
    enum RedactionWordList {
        /// Where they came from, and that copy's SHA-256 (a test compares the two when the file is there).
        static let source = "\(source)"
        static let sourceSHA256 = "\(pinnedSHA256)"
        /// How many there are.
        static let count = \(words.count)

        static let letters = [\(letters.joined(separator: ", "))]

    """
for letter in letters {
    file += "\n    static let \(letter) = \"\"\"\n" + (byLetter[letter] ?? []).joined(separator: "\n") + "\n\"\"\"\n"
}
file += "}\n"
do {
    try Data(file.utf8).write(to: output, options: .atomic)
} catch {
    fail("can't write \(output.path): \(error)")
}
print("make-redaction-words: \(words.count) words from \(source) in \(output.path)")
